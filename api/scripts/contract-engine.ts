/** contract/engine.ts is src/spec/engine.ts with its type import pointed at the spec-types.ts next to it. */
export function contractEngineSource(serverEngine: string): string {
  const from = 'from "./types.js"';
  if (!serverEngine.includes(from)) throw new Error(`src/spec/engine.ts no longer imports ${from}; update scripts/contract-engine.ts`);
  return `// Generated by \`npm run contract\` from api/src/spec/engine.ts. Do not edit; change the server file instead.\n`
    + serverEngine.replace(from, 'from "./spec-types.js"');
}
